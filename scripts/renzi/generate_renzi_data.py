KP_NAMES = [
    "看字认拼音",
    "看拼音认字",
    "拼音填空",
    "汉字填空",
    "读音判断",
]


def strip_distractor_opts(answer: str, pool: list[str], n: int = 4) -> list[str]:
    opts = [answer]
    for c in pool:
        if c != answer and c not in opts:
            opts.append(c)
        if len(opts) >= n:
            break
    while len(opts) < n:
        opts.append(f"备选{len(opts)}")
    return opts[1:]  # distractors only; caller inserts answer


def make_choice_options(answer: str, pool: list[str], rng: random.Random) -> list[str]:
    cands = [x for x in pool if x != answer]
    rng.shuffle(cands)
    opts = [answer] + cands[: max(0, 3)]
    while len(opts) < 4:
        opts.append(f"选项{len(opts)}")
    rng.shuffle(opts)
    return opts


def wrong_pinyin(py: str, pool: list[str], rng: random.Random) -> str:
    """生成一个看似合理的错误拼音：优先同声母/同韵母混淆。"""
    cands = [p for p in pool if p != py]
    if not cands:
        return py + "错"
    # 优先声母相同
    if len(py) >= 2:
        same_onset = [p for p in cands if p[:1] == py[:1] and p != py]
        if same_onset:
            return rng.choice(same_onset)
    return rng.choice(cands)


def unit_questions(unit_chars: Chars, unit_title: str, rng: random.Random) -> dict[str, list[dict[str, Any]]]:
    pys = [c[1] for c in unit_chars]
    chs = [c[0] for c in unit_chars]
    words = [c[2] for c in unit_chars]
    by_kp: dict[str, list[dict[str, Any]]] = {k: [] for k in KP_NAMES}
    qid = 0

    def next_id() -> int:
        nonlocal qid
        qid += 1
        return qid

    # KP1 看字认拼音 — choice
    for ch, py, word in unit_chars:
        wrong = wrong_pinyin(py, pys, rng)
        options = make_choice_options(py, [wrong] + [p for p in pys if p != py][:8], rng)
        by_kp["看字认拼音"].append({
            "id": next_id(),
            "type": "choice",
            "score": 5,
            "difficulty": 1 if len(ch) <= 4 else 2,
            "knowledge_point": "看字认拼音",
            "question": f"「{ch}」的正确读音是？（提示词：{word}）",
            "options": options,
            "answer": py,
            "explanation": f"「{ch}」读作 {py}，可以组词「{word}」。",
        })

    # KP2 看拼音认字 — choice
    for ch, py, word in unit_chars:
        options = make_choice_options(ch, chs, rng)
        by_kp["看拼音认字"].append({
            "id": next_id(),
            "type": "choice",
            "score": 5,
            "difficulty": 1,
            "knowledge_point": "看拼音认字",
            "question": f"拼音「{py}」对应的汉字是？（词：{word}）",
            "options": options,
            "answer": ch,
            "explanation": f"「{py}」写作「{ch}」，例如「{word}」。",
        })

    # KP3 拼音填空 — fill_blank_text
    for ch, py, word in rng.sample(unit_chars, min(len(unit_chars), 18)):
        by_kp["拼音填空"].append({
            "id": next_id(),
            "type": "fill_blank_text",
            "score": 5,
            "difficulty": 2,
            "knowledge_point": "拼音填空",
            "question": f"请写出「{ch}」的拼音（词：{word}）",
            "options": [],
            "answer": py,
            "explanation": f"「{ch}」的拼音是 {py}。",
        })

    # KP4 汉字填空 — fill_blank_text
    for ch, py, word in rng.sample(unit_chars, min(len(unit_chars), 18)):
        by_kp["汉字填空"].append({
            "id": next_id(),
            "type": "fill_blank_text",
            "score": 5,
            "difficulty": 2,
            "knowledge_point": "汉字填空",
            "question": f"请写出拼音「{py}」对应的汉字（词：{word}）",
            "options": [],
            "answer": ch,
            "explanation": f"「{py}」对应的汉字是「{ch}」。",
        })

    # KP5 读音判断 — true/false（一半对一半错）
    sample = rng.sample(unit_chars, min(len(unit_chars), 16))
    for i, (ch, py, word) in enumerate(sample):
        is_true = i % 2 == 0
        shown = py if is_true else wrong_pinyin(py, pys, rng)
        answer = "对" if is_true else "错"
        by_kp["读音判断"].append({
            "id": next_id(),
            "type": "true_false",
            "score": 3,
            "difficulty": 1 if is_true else 2,
            "knowledge_point": "读音判断",
            "question": f"「{ch}」读作 {shown}。（词：{word}）",
            "options": [],
            "answer": answer,
            "explanation": (
                f"正确。「{ch}」的读音是 {py}。"
                if is_true
                else f"错误。「{ch}」应读 {py}，不是 {shown}。"
            ),
        })

    return by_kp


def build_book(book_key: str) -> tuple[dict[str, Any], dict[str, Any]]:
    meta = BOOKS[book_key]
    grade = meta["grade"]
    semester = meta["semester"]
    grade_name = GRADE_NAMES[grade]
    sem_name = SEM_NAMES[semester]
    stem = f"义务教育教科书·认字{grade_name}年级{sem_name}"
    textbook = f"统编版小学认字{grade_name}年级{sem_name}"
    book_id = f"renzi-{book_key}"

    outline: dict[str, Any] = {
        "textbook": textbook,
        "units": [],
    }

    rng = random.Random(f"renzi-{book_key}")

    total_chars = 0
    total_questions = 0

    for u_idx, unit in enumerate(meta["units"], start=1):
        chars: Chars = unit["chars"]
        # 去重（保留首次出现的读音/组词）
        seen: set[str] = set()
        uniq: Chars = []
        for c in chars:
            if c[0] not in seen:
                seen.add(c[0])
                uniq.append(c)
        chars = uniq
        total_chars += len(chars)

        by_kp = unit_questions(chars, unit["title"], rng)

        unit_test_q: list[dict[str, Any]] = []
        exam_q: list[dict[str, Any]] = []
        knowledge_summary = []
        kps = []

        for kp in KP_NAMES:
            qs = by_kp[kp]
            if not qs:
                continue
            kps.append({
                "name": kp,
                "description": {
                    "看字认拼音": f"在「{unit['title']}」中认读生字并选择正确拼音。",
                    "看拼音认字": f"根据拼音选出「{unit['title']}」对应的汉字。",
                    "拼音填空": "给出生字，正确写出拼音（含声调）。",
                    "汉字填空": "给出拼音，正确写出对应的汉字。",
                    "读音判断": "判断「字—拼音」对应关系是否正确。",
                }[kp],
                "difficulty": 1 if kp in ("看字认拼音", "看拼音认字", "读音判断") else 2,
                "question_types": {
                    "看字认拼音": ["选择"],
                    "看拼音认字": ["选择"],
                    "拼音填空": ["填空"],
                    "汉字填空": ["填空"],
                    "读音判断": ["判断"],
                }[kp],
            })
            knowledge_summary.append({
                "point": kp,
                "core_concept": {
                    "看字认拼音": f"掌握本单元 {len(chars)} 个生字的正确读音。",
                    "看拼音认字": "建立拼音到字形的稳定映射。",
                    "拼音填空": "巩固声母、韵母与声调的书写。",
                    "汉字填空": "在语境提示下从拼音还原字形。",
                    "读音判断": "辨析易错读音与形近字读音。",
                }[kp],
                "key_formula": {
                    "看字认拼音": "看字 → 想读音 → 对选项",
                    "看拼音认字": "拼读 → 想字形 → 对选项",
                    "拼音填空": "字 → 声母 + 韵母 + 声调",
                    "汉字填空": "拼音 → 词义线索 → 写字",
                    "读音判断": "对照标准读音，判断对/错",
                }[kp],
                "common_mistakes": [
                    "声调标错位置",
                    "前后鼻音混淆（in/ing，en/eng）",
                    "形近字读音混用",
                ],
                "tips": f"先跟读「{unit['title']}」生字表，再做练习；错题进错题本复习。",
            })
            unit_test_q.extend(qs)
            # exam 抽样：每个 KP 取 3-4 题
            exam_q.extend(rng.sample(qs, min(len(qs), 3)))

        # exam 再补一些混合题
        all_q = unit_test_q[:]
        rng.shuffle(all_q)
        for q in all_q[: max(0, 12 - len(exam_q))]:
            if q not in exam_q:
                exam_q.append({**q})

        total_questions += len(unit_test_q) + len(exam_q)

        outline["units"].append({
            "unit_number": u_idx,
            "title": unit["title"],
            "knowledge_points": kps,
        })

        quiz = {
            "textbook": textbook,
            "unit": unit["title"],
            "unit_number": u_idx,
            "unit_test": {
                "title": f"第{u_idx}单元「{unit['title']}」认字与拼音练习",
                "total_score": 100,
                "time_minutes": 20,
                "questions": unit_test_q,
            },
            "exam": {
                "title": f"第{u_idx}单元「{unit['title']}」综合挑战",
                "total_score": 100,
                "time_minutes": 15,
                "questions": exam_q[:15],
            },
            "knowledge_summary": knowledge_summary,
        }

        quiz_path = QUIZ_DIR / f"{stem}_unit{u_idx}.json"
        quiz_path.write_text(json.dumps(quiz, ensure_ascii=False, indent=2), encoding="utf-8")

    outline_path = OUTLINE_DIR / f"{stem}.json"
    outline_path.write_text(json.dumps(outline, ensure_ascii=False, indent=2), encoding="utf-8")

    return (
        {"book_id": book_id, "stem": stem, "chars": total_chars, "questions": total_questions},
        outline,
    )


def main() -> None:
    OUTLINE_DIR.mkdir(parents=True, exist_ok=True)
    QUIZ_DIR.mkdir(parents=True, exist_ok=True)
    print("生成认字科目数据…")
    total_c = total_q = 0
    for key in BOOKS:
        info, _ = build_book(key)
        print(
            f"  ✓ {info['stem']}: {info['chars']} 生字 / {info['questions']} 题"
        )
        total_c += info["chars"]
        total_q += info["questions"]
    print(f"合计: {total_c} 生字 / {total_q} 题 / {len(BOOKS)} 本")
    print(f"输出: {OUTLINE_DIR}")
    print(f"输出: {QUIZ_DIR}")


if __name__ == "__main__":
    main()
